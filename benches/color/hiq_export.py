#!/usr/bin/env python3
"""Exports HiQ's shipped colour-classifier parameters to `hiq_models.txt`, as shipped.

Nothing is refitted: each file is parsed the way its Java loader parses it
(`QDA.getInstance`, `LayeredSVM.getInstance`, and the bench's `Configs.readCoefficients`
for the CMI weights), and the numbers are written back out with `repr`, which round-trips
every double exactly. Run from the qrism root:

    python3 benches/color/hiq_export.py [--hiq ~/Projects/hiq/HiQ/hiq-decoder]

What the parameters mean, and where they come from, is in `hiq_port.md`.
"""
import argparse
import hashlib
import os
import subprocess

QDA = "candidate_classifiers/Qmodel_CMI.txt"
CMI = "candidate_classifiers/Qmodel_CMI_coef.txt"
LSVM = "candidate_classifiers/layeredSVMs_ip6plus_mixed_new_aug.txt"
OUT = os.path.join(os.path.dirname(__file__), "hiq_models.txt")


def fields(line):
    # Java's `split(" ")`: keeps empty fields, which the loaders never reach.
    return line.rstrip("\n").split(" ")


def read_qda(path):
    lines = open(path).readlines()
    n, dim = (int(x) for x in fields(lines[0])[:2])
    groups = [int(x) for x in fields(lines[1])[:n]]
    prior = [float(x) for x in fields(lines[2])[:n]]
    means = [[float(x) for x in fields(lines[3 + i])[:dim]] for i in range(n)]
    base = 3 + n
    inv = [
        [float(x) for r in range(dim) for x in fields(lines[base + c * dim + r])[:dim]]
        for c in range(n)
    ]
    dets = [float(x) for x in fields(lines[base + n * dim])[:n]]
    assert dim == 3 and n == 8 and sorted(groups) == list(range(8))
    return groups, prior, means, inv, dets


def read_cmi(path):
    # `Configs.readCoefficients`: a row count, then rows split on whitespace runs.
    lines = open(path).read().split("\n")
    rows = int(lines[0].strip())
    out = [[float(x) for x in lines[1 + i].split()] for i in range(rows)]
    assert rows == 1 and len(out[0]) == 5
    return out[0]


def read_lsvm(path):
    lines = open(path).read().split("\n")
    layers = int(lines[0])
    at, out = 1, []
    for _ in range(layers):
        dim = int(lines[at])
        w = [float(x) for x in fields(lines[at + 1])[:dim]]
        b = float(lines[at + 2])
        assert dim in (3, 10, 20) and len(w) == dim
        out.append((w, b))
        at += 3
    assert layers == 3
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--hiq", default=os.path.expanduser("~/Projects/hiq/HiQ/hiq-decoder"))
    a = ap.parse_args()
    src = lambda rel: os.path.join(a.hiq, rel)  # noqa: E731
    commit = subprocess.run(["git", "-C", a.hiq, "rev-parse", "--short", "HEAD"],
                            capture_output=True, text=True).stdout.strip() or "unknown"

    groups, prior, means, inv, dets = read_qda(src(QDA))
    cmi = read_cmi(src(CMI))
    lsvm = read_lsvm(src(LSVM))

    r = lambda xs: " ".join(repr(float(x)) for x in xs)  # noqa: E731
    out = ["# Generated by hiq_export.py from hiq-decoder " + commit + ". Do not edit."]
    for rel in (QDA, CMI, LSVM):
        digest = hashlib.sha256(open(src(rel), "rb").read()).hexdigest()
        out.append(f"# {rel} sha256 {digest}")
    out.append("# qda.*: per class in file order; invcov is the stored inverse covariance,")
    out.append("# row-major; halflogdet is the stored log(det cov)/2.")
    out.append("qda.groups " + " ".join(str(g) for g in groups))
    out.append("qda.logprior " + r(prior))
    for c in range(8):
        out.append(f"qda.mean.{c} " + r(means[c]))
    for c in range(8):
        out.append(f"qda.invcov.{c} " + r(inv[c]))
    out.append("qda.halflogdet " + r(dets))
    out.append("# CMI weights in sampler slot order: centre, left, right, up, down.")
    out.append("cmi.weights " + r(cmi))
    out.append("# One SVM per layer (R, G, B); 3, 10 or 20 weights for linear, quadratic, cubic.")
    for i, (w, b) in enumerate(lsvm):
        out.append(f"lsvm.w.{i} " + r(w))
        out.append(f"lsvm.b.{i} " + r([b]))
    with open(OUT, "w") as f:
        f.write("\n".join(out) + "\n")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
